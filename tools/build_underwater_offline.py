#!/usr/bin/env python3
"""Embed the lake modules for the existing double-click/file:// fallback."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent

def source(rel):
    return json.dumps((root / 'meadow' / rel).read_text(encoding='utf-8'), ensure_ascii=False)

bundle = '''// Generated by tools/build_underwater_offline.py; edit the source modules instead.
// Includes Abyssal Garden procedural code, copyright (c) 2026 Maksymilian Dendura.
// MIT license: ./abyssal/LICENSE.
(function () {
  var B = function (code) { return URL.createObjectURL(new Blob([code], {type: 'text/javascript'})); };
'''
bundle += '  var math = B(' + source('abyssal/math.js') + ');\n'
bundle += '  var meshes = B(' + source('abyssal/meshes.js') + '.replace("./math.js", math));\n'
bundle += '  var audio = B(' + source('abyssal/audio.js') + '.replace("./math.js", math));\n'
bundle += '  var diving = B(' + source('diving.js') + ');\n'
bundle += '  var garden = B(' + source('underwater.js') + '.replace("./abyssal/math.js", math).replace("./abyssal/meshes.js", meshes));\n'
bundle += '''  var imports = window.SSW_LAKE_IMPORTS = {};
  imports[new URL('./underwater.js', document.baseURI).href] = garden;
  imports[new URL('./diving.js', document.baseURI).href] = diving;
  imports[new URL('./abyssal/audio.js', document.baseURI).href] = audio;
})();
'''
(root / 'meadow/abyssal-offline.js').write_text(bundle, encoding='utf-8')
print('已更新 meadow/abyssal-offline.js')
